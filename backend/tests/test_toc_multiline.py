"""A wrapped TOC entry — a list item whose `lines` were preserved because it wraps onto
two source lines, but whose LAST line still ends in a dot leader + page number — must
render as ONE paragraph with the marker written once and a right-aligned dot-leader tab
stop (exactly like a single-line TOC entry via `_toc_split`/`_render_toc`), not as two
literal preserved lines. A non-TOC multi-line item (no leader/page number) keeps its
line-break rendering unchanged."""
from docx import Document
from docx.enum.text import WD_TAB_ALIGNMENT, WD_TAB_LEADER

from models import ListItemBlock, SemanticDocument
from renderers.docx_renderer import render_docx


def test_wrapped_toc_entry_reflows_as_single_leader_row(tmp_path):
    doc = SemanticDocument(blocks=[
        ListItemBlock(
            marker="2.2.1.2.2.", level=0,
            lines=["Profiling of Metabolites of X Generated by",
                   "Hepatocytes from Mouse (MC11M-0047) ................. 8"],
            text="Profiling of Metabolites of X Generated by Hepatocytes from Mouse "
                 "(MC11M-0047)",
        ),
    ])
    out = str(tmp_path / "toc.docx")
    render_docx(doc, out, str(tmp_path))
    d = Document(out)
    paras = [p for p in d.paragraphs if p.text.strip()]
    assert len(paras) == 1                        # single paragraph for the entry
    p = paras[0]
    assert p.text.count("2.2.1.2.2.") == 1         # marker written exactly once
    assert "\n" not in p.text                      # no preserved line break — one leader row
    tab_stops = list(p.paragraph_format.tab_stops)
    assert len(tab_stops) == 1
    assert tab_stops[0].alignment == WD_TAB_ALIGNMENT.RIGHT
    assert tab_stops[0].leader == WD_TAB_LEADER.DOTS
    assert p.text.rstrip().endswith("8")           # page number is the trailing text


def test_non_toc_multiline_item_keeps_line_break(tmp_path):
    doc = SemanticDocument(blocks=[
        ListItemBlock(
            marker="1)", level=0,
            lines=["First control line", "Second control line no leader"],
            text="First control line Second control line no leader",
        ),
    ])
    out = str(tmp_path / "control.docx")
    render_docx(doc, out, str(tmp_path))
    d = Document(out)
    paras = [p for p in d.paragraphs if p.text.strip()]
    assert len(paras) == 1
    p = paras[0]
    assert p.text == "1) First control line\nSecond control line no leader"
    assert list(p.paragraph_format.tab_stops) == []
