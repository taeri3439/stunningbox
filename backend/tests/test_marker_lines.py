"""A wrapped TOC/list entry carries BOTH `marker` (e.g. "2.2.1.2.2.") and the raw first
recovered line, which may start with that same marker text ("2.2.1.2.2. Profiling of
Metabolites..."). Rendering `"{marker} " + lines` would then duplicate the marker
("2.2.1.2.2. 2.2.1.2.2. Profiling..."). The reconciler must strip an embedded marker
*prefix* (marker + whitespace boundary) from the first recovered line, while preserving
the existing whole-line-drop behavior when the marker sits on its own line, and leaving
near-miss / marker-less entries untouched."""
from models import RawDocument, RawPage, RawSpan
from pipeline.reconciler import reconcile


def _reconcile_list_item(spans, pb, tmp_path):
    raw = RawDocument(pages=[RawPage(width=595, height=842, spans=spans)])
    doc, _ = reconcile(raw, [[pb]], str(tmp_path / "x.pdf"), str(tmp_path), source_lang="en")
    return [b for b in doc.blocks if b.type == "list_item"][0]


def test_marker_prefix_stripped_from_first_recovered_line(tmp_path):
    # marker embedded at the head of line 0 ("2.2.1.2.2. Profiling...") — strip the
    # prefix so the renderer's "{marker} " + lines doesn't render it twice.
    spans = [
        RawSpan(id="p0b0l0s0", page=0, text="2.2.1.2.2.",
                bbox=(72, 100, 110, 112), size=11),
        RawSpan(id="p0b0l0s1", page=0, text="Profiling of Metabolites of X Generated by",
                bbox=(115, 100, 500, 112), size=11),
        RawSpan(id="p0b0l1s0", page=0,
                text="Hepatocytes from Mouse (MC11M-0047) ................. 8",
                bbox=(72, 114, 500, 126), size=11),
    ]
    pb = {
        "type": "list_item", "marker": "2.2.1.2.2.", "level": 0,
        "text": "Profiling of Metabolites of X Generated by Hepatocytes from Mouse "
                "(MC11M-0047) 8",
        "source_span_ids": ["p0b0l0s0", "p0b0l0s1", "p0b0l1s0"],
    }
    li = _reconcile_list_item(spans, pb, tmp_path)
    assert li.marker == "2.2.1.2.2."
    assert li.lines is not None
    assert li.lines[0] == "Profiling of Metabolites of X Generated by"
    assert li.lines[1] == "Hepatocytes from Mouse (MC11M-0047) ................. 8"


def test_marker_whole_line_still_dropped(tmp_path):
    # existing behavior preserved: the marker recovered as its own (first) line is
    # dropped entirely, not stripped-as-prefix.
    spans = [
        RawSpan(id="p0b0l0s0", page=0, text="4.", bbox=(72, 100, 90, 112), size=11),
        RawSpan(id="p0b0l1s0", page=0, text="Nonclinical Overview .......... 2",
                bbox=(108, 100, 500, 112), size=11),
    ]
    pb = {
        "type": "list_item", "marker": "4.", "level": 0,
        "text": "Nonclinical Overview .......... 2",
        "source_span_ids": ["p0b0l0s0", "p0b0l1s0"],
    }
    li = _reconcile_list_item(spans, pb, tmp_path)
    assert li.marker == "4."
    assert li.lines is None              # single remaining line -> reflow, not preserved
    assert li.text.startswith("Nonclinical Overview")


def test_near_miss_marker_prefix_untouched(tmp_path):
    # "2.2.1.2.20" is NOT "2.2.1.2.2." + whitespace (the extra digit collides with the
    # marker's trailing dot) — must not be treated as an embedded-marker prefix.
    spans = [
        RawSpan(id="p0b0l0s0", page=0, text="2.2.1.2.20 something",
                bbox=(72, 100, 300, 112), size=11),
        RawSpan(id="p0b0l1s0", page=0, text="Another line here ................. 3",
                bbox=(72, 114, 500, 126), size=11),
    ]
    pb = {
        "type": "list_item", "marker": "2.2.1.2.2.", "level": 0,
        "text": "2.2.1.2.20 something Another line here 3",
        "source_span_ids": ["p0b0l0s0", "p0b0l1s0"],
    }
    li = _reconcile_list_item(spans, pb, tmp_path)
    assert li.lines is not None
    assert li.lines[0] == "2.2.1.2.20 something"
    assert li.lines[1] == "Another line here ................. 3"


def test_no_marker_lines_untouched(tmp_path):
    spans = [
        RawSpan(id="p0b0l0s0", page=0, text="Some Title Wrapped First",
                bbox=(72, 100, 300, 112), size=11),
        RawSpan(id="p0b0l1s0", page=0, text="Continued text ................. 5",
                bbox=(72, 114, 500, 126), size=11),
    ]
    pb = {
        "type": "list_item", "level": 0,
        "text": "Some Title Wrapped First Continued text 5",
        "source_span_ids": ["p0b0l0s0", "p0b0l1s0"],
    }
    li = _reconcile_list_item(spans, pb, tmp_path)
    assert li.lines is not None
    assert li.lines[0] == "Some Title Wrapped First"
    assert li.lines[1] == "Continued text ................. 5"
